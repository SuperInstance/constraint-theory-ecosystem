def compile_to_c(constraints: Constraints, output_path: Union[str, Path]) -> Path:
    """
    Generate a standalone C file with:
    - Constraint bounds as static arrays
    - flux_check_exact() hot path inlined
    - main() with benchmark harness
    - Compiles with gcc -O3 -mavx2 automatically
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    n = len(constraints)
    names = [c.get("name", f"C{i}") for i, c in enumerate(constraints)]
    lo_vals = [float(c["lo"]) for c in constraints]
    hi_vals = [float(c["hi"]) for c in constraints]

    lines: List[str] = []
    a = lines.append

    # ── Header ──────────────────────────────────────────────
    a("/*")
    a(" * FLUX Exact Constraint Engine — Auto-generated C Deployment")
    a(f" * Constraints: {n}")
    for i, nm in enumerate(names):
        a(f" *   [{i}] {nm}: [{lo_vals[i]}, {hi_vals[i]}]")
    a(" * Generated by flux_deploy.compile_to_c()")
    a(" */")
    a("")
    a("#include <stdio.h>")
    a("#include <stdlib.h>")
    a("#include <string.h>")
    a("#include <math.h>")
    a("#include <stdint.h>")
    a("#include <stdbool.h>")
    a("#include <time.h>")
    a("")
    a(f"#define N_CONSTRAINTS {n}")
    a(f"#define FLUX_EXACT_MAX_CONSTRAINTS 8")
    a("")

    # ── Bounds arrays ───────────────────────────────────────
    a("/* Constraint bounds */")
    lo_strs = ", ".join(_c_float(v) for v in lo_vals)
    hi_strs = ", ".join(_c_float(v) for v in hi_vals)
    a(f"static const float BOUNDS_LO[FLUX_EXACT_MAX_CONSTRAINTS] = {{{lo_strs}}};")
    a(f"static const float BOUNDS_HI[FLUX_EXACT_MAX_CONSTRAINTS] = {{{hi_strs}}};")
    a("")
    a("static const char* const CONSTRAINT_NAMES[FLUX_EXACT_MAX_CONSTRAINTS] = {")
    for nm in names:
        a(f'    "{_c_escape(nm)}",')
    a("};")
    a("")

    # ── Severity table ──────────────────────────────────────
    a("static const uint8_t SEVERITY_TABLE[9] = {0, 1, 1, 2, 2, 3, 3, 3, 3};")
    a("")

    # ── Hot path: flux_check_exact ──────────────────────────
    a("/* ── Hot path: returns error_mask (0 = pass) ──────── */")
    a("")
    a("static inline uint8_t flux_check_exact(float val) {")
    a("    if (val != val) return (1u << N_CONSTRAINTS) - 1u;  /* NaN violates all */")
    a("    uint8_t mask = 0;")
    for i in range(n):
        a(f"    if (val < BOUNDS_LO[{i}] || val > BOUNDS_HI[{i}])")
        a(f"        mask |= (1u << {i});")
    a("    return mask;")
    a("}")
    a("")

    # ── Batch check (scalar) ────────────────────────────────
    a("static void flux_check_batch(const float* values, int count, uint8_t* masks) {")
    a("    for (int i = 0; i < count; i++) {")
    a("        masks[i] = flux_check_exact(values[i]);")
    a("    }")
    a("}")
    a("")

    # ── Severity helper ─────────────────────────────────────
    a("static const char* severity_name(uint8_t mask) {")
    a("    uint8_t count = 0; uint8_t m = mask;")
    a("    while (m) { count++; m &= m - 1; }")
    a("    switch (SEVERITY_TABLE[count > 8 ? 8 : count]) {")
    a("        case 0: return \"PASS\";")
    a("        case 1: return \"CAUTION\";")
    a("        case 2: return \"WARNING\";")
    a("        case 3: return \"CRITICAL\";")
    a("        default: return \"UNKNOWN\";")
    a("    }")
    a("}")
    a("")

    # ── Print result helper ─────────────────────────────────
    a("static void print_result(float val, uint8_t mask) {")
    a('    printf("  val=%.4f  mask=0x%02x  severity=%s", val, mask, severity_name(mask));')
    a("    if (mask) {")
    a('        printf("  violated:");')
    for i in range(n):
        a(f'        if (mask & (1u << {i})) printf(" {names[i]}");')
    a("    }")
    a('    printf("\\n");')
    a("}")
    a("")

    # ── Timing helper ───────────────────────────────────────
    a("static double now_sec(void) {")
    a("    struct timespec ts;")
    a("    clock_gettime(CLOCK_MONOTONIC, &ts);")
    a("    return ts.tv_sec + ts.tv_nsec * 1e-9;")
    a("}")
    a("")

    # ── Main: correctness + benchmark ───────────────────────
    a("int main(void) {")
    a(f'    printf("=== FLUX Exact Check — Auto-generated ({n} constraints) ===\\n\\n");')
    a("")
    a("    /* Correctness tests */")
    a('    printf("Correctness tests:\\n");')
    a("    int pass = 0, fail = 0;")
    a("")

    # Pre-compute expected error_masks for test values in Python
    # This is critical because a value at constraint i's boundary may
    # violate other constraints (e.g., -40 passes coolant but fails engine_rpm).
    def _expected_mask(val):
        if math.isnan(val):
            return (1 << n) - 1
        mask = 0
        for j in range(n):
            if val < lo_vals[j] or val > hi_vals[j]:
                mask |= (1 << j)
        return mask

    a("    /* Correctness tests with pre-computed expected masks */")
    a("")

    # Test each constraint boundary
    test_cases = []
    for i in range(n):
        lo_c = _c_float(lo_vals[i])
        hi_c = _c_float(hi_vals[i])
        # lo boundary
        test_cases.append((f"{names[i]} lo={lo_c}", lo_vals[i], _expected_mask(lo_vals[i])))
        # hi boundary
        test_cases.append((f"{names[i]} hi={hi_c}", hi_vals[i], _expected_mask(hi_vals[i])))
        # Just outside
        if lo_vals[i] != hi_vals[i]:
            below = lo_vals[i] - 0.001
            above = hi_vals[i] + 0.001
            test_cases.append((f"{names[i]} below lo", below, _expected_mask(below)))
            test_cases.append((f"{names[i]} above hi", above, _expected_mask(above)))

    # NaN test
    test_cases.append(("NaN", float('nan'), (1 << n) - 1))

    for desc, val, expected in test_cases:
        if math.isnan(val):
            val_c = "NAN"
        else:
            val_c = _c_float(val)
        a(f'    {{ uint8_t got = flux_check_exact({val_c});')
        a(f'      uint8_t exp = 0x{expected:02x};')
        a(f'      if (got == exp) pass++;')
        a(f'      else {{ fail++; printf("  FAIL: {desc} got=0x%02x exp=0x%02x\\n", got, exp); }}')
        a(f'    }}')

    a("")
    a("")
    a('    printf("  Passed: %d / %d\\n\\n", pass, pass + fail);')
    a("")
    a("    /* Benchmark */")
    a("    const int ITERS = 10000000;")
    a("    float* vals = malloc(ITERS * sizeof(float));")
    a("    uint8_t* masks_out = malloc(ITERS);")
    a("    for (int i = 0; i < ITERS; i++) vals[i] = (float)((i % 1000) - 500);")
    a("")
    a("    double t0 = now_sec();")
    a("    flux_check_batch(vals, ITERS, masks_out);")
    a("    double elapsed = now_sec() - t0;")
    a("    double rate = ITERS / elapsed;")
    a('    printf("Benchmark (%d constraints, %d iters):\\n", N_CONSTRAINTS, ITERS);')
    a('    printf("  Scalar: %.1fM checks/sec (%.3fms)\\n", rate / 1e6, elapsed * 1000);')
    a("")
    a("    free(vals);")
    a("    free(masks_out);")
    a("")
    a("    return fail > 0 ? 1 : 0;")
    a("}")
    a("")

    output_path.write_text("\n".join(lines), encoding="utf-8")
    return output_path


