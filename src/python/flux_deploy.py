def compile_to_asm_arm(constraints: Constraints, output_path: Union[str, Path]) -> Path:
    """
    Generate ARM Cortex-M4 assembly:
    - Thumb-2 instructions
    - Hard-float comparisons (FPU)
    - Inlined constraint loop
    - Returns error_mask in r0
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    n = len(constraints)
    names = [c.get("name", f"C{i}") for i, c in enumerate(constraints)]
    lo_vals = [float(c["lo"]) for c in constraints]
    hi_vals = [float(c["hi"]) for c in constraints]

    lines: List[str] = []
    a = lines.append

    a("    .syntax unified")
    a("    .cpu cortex-m4")
    a("    .fpu fpv4-sp-d16")
    a("    .thumb")
    a("")
    a("    .section .rodata")
    a("    .align 2")
    a("")

    # ── Constants pool ──────────────────────────────────────
    a("bounds_lo:")
    for v in lo_vals:
        a(f"    .float {_arm_float(v)}")
    a("")
    a("bounds_hi:")
    for v in hi_vals:
        a(f"    .float {_arm_float(v)}")
    a("")
    a("constraint_names:")
    for nm in names:
        a(f'    .asciz "{_c_escape(nm)}"')
        a("    .align 1")
    a("")

    # ── Text section ────────────────────────────────────────
    a("    .section .text")
    a("    .align 2")
    a("    .global flux_check_exact")
    a("    .thumb_func")
    a("")
    a("    /// flux_check_exact(float val) -> uint8_t error_mask")
    a("    /// Input: s0 = value to check")
    a("    /// Output: r0 = error_mask (0 = all pass)")
    a("    /// Clobbers: r1, r2, s1, s2, s3")
    a("flux_check_exact:")
    a("    push    {r4, r5, lr}")
    a("")
    a("    /// Initialize mask = 0")
    a("    movs    r0, #0              @ error_mask = 0")
    a("    movs    r4, #0              @ constraint index = 0")
    a(f"    movs    r5, #{n}             @ total constraints")
    a("")
    a("    /// NaN check: compare val with itself")
    a("    vcmp.f32    s0, s0")
    a("    vmrs    APSR_nzcv, fpscr")
    a("    beq     .L_not_nan")
    a(f"    mvn     r0, #(0xFF >> {8 - n})  @ NaN → all bits set")
    a("    b       .L_done")
    a("")
    a(".L_not_nan:")
    a("    /// Load bounds table address")
    a("    ldr     r1, =bounds_lo")
    a("    ldr     r2, =bounds_hi")
    a("")
    a(".L_check_loop:")
    a("    cmp     r4, r5")
    a("    bge     .L_done")
    a("")
    a("    /// Load lo[i] and hi[i]")
    a("    adds    r3, r1, r4, lsl #2  @ &bounds_lo[i]")
    a("    vldr.32 s1, [r3]            @ s1 = lo[i]")
    a("    adds    r3, r2, r4, lsl #2  @ &bounds_hi[i]")
    a("    vldr.32 s2, [r3]            @ s2 = hi[i]")
    a("")
    a("    /// Check val < lo[i]")
    a("    vcmp.f32    s0, s1")
    a("    vmrs    APSR_nzcv, fpscr")
    a("    bmi     .L_violate           @ val < lo → violate")
    a("")
    a("    /// Check val > hi[i]")
    a("    vcmp.f32    s0, s2")
    a("    vmrs    APSR_nzcv, fpscr")
    a("    bgt     .L_violate           @ val > hi → violate")
    a("")
    a("    b       .L_next")
    a("")
    a(".L_violate:")
    a("    /// Set bit i in error_mask")
    a("    movs    r3, #1")
    a("    lsls    r3, r4              @ r3 = 1 << i")
    a("    orrs    r0, r3              @ mask |= (1 << i)")
    a("")
    a(".L_next:")
    a("    adds    r4, #1              @ i++")
    a("    b       .L_check_loop")
    a("")
    a(".L_done:")
    a("    /// r0 = error_mask, return")
    a("    pop     {r4, r5, pc}")
    a("")
    a("")

    # ── Batch check ─────────────────────────────────────────
    a("    .global flux_check_batch")
    a("    .thumb_func")
    a("")
    a("    /// flux_check_batch(float* values, int count, uint8_t* masks)")
    a("    /// r0 = values ptr, r1 = count, r2 = masks ptr")
    a("flux_check_batch:")
    a("    push    {r4, r5, r6, lr}")
    a("    mov     r4, r0              @ r4 = values")
    a("    mov     r5, r1              @ r5 = count")
    a("    mov     r6, r2              @ r6 = masks")
    a("    movs    r3, #0              @ i = 0")
    a("")
    a(".L_batch_loop:")
    a("    cmp     r3, r5")
    a("    bge     .L_batch_done")
    a("")
    a("    /// Load value[i] into s0")
    a("    adds    r0, r4, r3, lsl #2")
    a("    vldr.32 s0, [r0]")
    a("")
    a("    /// Call check (tail-call friendly inline)")
    a("    push    {r3, r6}           @ save i and masks ptr")
    a("    bl      flux_check_exact")
    a("    pop     {r3, r6}")
    a("")
    a("    /// Store result mask[i] = r0")
    a("    strb    r0, [r6, r3]")
    a("")
    a("    adds    r3, #1")
    a("    b       .L_batch_loop")
    a("")
    a(".L_batch_done:")
    a("    pop     {r4, r5, r6, pc}")
    a("")

    s_path = output_path if output_path.suffix == ".s" else output_path.with_suffix(".s")
    s_path.write_text("\n".join(lines), encoding="utf-8")
    return s_path


def _arm_float(v: float) -> str:
    if math.isinf(v):
        return "1.0e38" if v > 0 else "-1.0e38"  # Approximate for ARM float
    return repr(v)


