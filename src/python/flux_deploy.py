_TARGETS = {
    "c": ("C (gcc)", compile_to_c),
    "wasm": ("WebAssembly", compile_to_wasm),
    "verilog": ("Verilog (FPGA)", compile_to_verilog),
    "arm": ("ARM Cortex-M4", compile_to_asm_arm),
}

ALL_TARGETS = list(_TARGETS.keys())


def deploy(
    target: str,
    constraints: Constraints,
    output_dir: Union[str, Path],
) -> Dict[str, Any]:
    """
    Master deployment function.

    Args:
        target: One of 'c', 'wasm', 'verilog', 'arm', or 'all'
        constraints: List of constraint dicts with lo, hi, name
        output_dir: Directory for output files

    Returns:
        Dict with deployment results per target.
    """
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    targets = ALL_TARGETS if target == "all" else [target]
    results: Dict[str, Any] = {}

    for t in targets:
        if t not in _TARGETS:
            results[t] = {"status": "error", "message": f"Unknown target: {t}"}
            continue

        label, compiler = _TARGETS[t]
        t0 = time.time()

        try:
            # Determine output path
            ext_map = {"c": ".c", "wasm": ".wasm", "verilog": ".v", "arm": ".s"}
            out_path = output_dir / f"flux_check{ext_map[t]}"

            # Compile
            generated = compiler(constraints, out_path)
            elapsed = time.time() - t0

            result: Dict[str, Any] = {
                "status": "ok",
                "target": t,
                "label": label,
                "output": str(generated),
                "size_bytes": generated.stat().st_size,
                "compile_time_ms": round(elapsed * 1000, 1),
            }

            # Try to actually compile if tools available
            if t == "c":
                result.update(_try_compile_c(generated, output_dir))
            elif t == "wasm" and generated.suffix == ".wasm":
                result["wasm_compiled"] = True
                result["wasm_size"] = generated.stat().st_size

            results[t] = result

        except Exception as e:
            results[t] = {
                "status": "error",
                "target": t,
                "message": str(e),
                "compile_time_ms": round((time.time() - t0) * 1000, 1),
            }

    # Write README
    _write_readme(constraints, output_dir, results, targets)

    return results


def _try_compile_c(c_path: Path, output_dir: Path) -> Dict[str, Any]:
    """Try to compile generated C with gcc and run it."""
    result: Dict[str, Any] = {}
    binary = output_dir / "flux_check"

    # Try gcc
    try:
        comp = subprocess.run(
            ["gcc", "-O3", "-mavx2", "-lm", "-o", str(binary), str(c_path)],
            capture_output=True, text=True, timeout=30,
        )
        if comp.returncode == 0:
            result["gcc_compiled"] = True
            result["binary_size"] = binary.stat().st_size

            # Try running
            try:
                run = subprocess.run(
                    [str(binary)],
                    capture_output=True, text=True, timeout=10,
                )
                result["run_exit_code"] = run.returncode
                result["run_output"] = run.stdout[:2000]
                if run.returncode == 0:
                    result["passed"] = True
                else:
                    result["passed"] = False
            except Exception as e:
                result["run_error"] = str(e)
        else:
            result["gcc_compiled"] = False
            result["gcc_errors"] = comp.stderr[:1000]
    except FileNotFoundError:
        result["gcc_available"] = False
    except subprocess.TimeoutExpired:
        result["gcc_timeout"] = True

    return result


def _write_readme(
    constraints: Constraints,
    output_dir: Path,
    results: Dict[str, Any],
    targets: List[str],
) -> None:
    """Write a deployment README."""
    n = len(constraints)
    names = [c.get("name", f"C{i}") for i, c in enumerate(constraints)]

    lines: List[str] = []
    a = lines.append

    a("# FLUX Constraint Engine — Deployment Package")
    a("")
    a(f"**Constraints:** {n}")
    a("")
    a("| # | Name | Lower Bound | Upper Bound |")
    a("|---|------|-------------|-------------|")
    for i, nm in enumerate(names):
        a(f"| {i} | {nm} | {constraints[i]['lo']} | {constraints[i]['hi']} |")
    a("")

    a("## Targets")
    a("")
    for t in targets:
        r = results.get(t, {})
        status = r.get("status", "unknown")
        label = _TARGETS.get(t, (t,))[0]
        a(f"### {label}")
        a(f"- Status: {status}")
        if "output" in r:
            a(f"- Output: `{r['output']}`")
        if "size_bytes" in r:
            a(f"- Size: {r['size_bytes']} bytes")
        if "compile_time_ms" in r:
            a(f"- Compile time: {r['compile_time_ms']}ms")
        if r.get("gcc_compiled"):
            a(f"- GCC compiled: ✓")
            if "binary_size" in r:
                a(f"- Binary size: {r['binary_size']} bytes")
            if r.get("passed"):
                a(f"- Tests: **PASSED** ✓")
            elif "run_output" in r:
                a(f"- Tests: see output below")
        if r.get("wasm_compiled"):
            a(f"- WASM binary: ✓ ({r.get('wasm_size', '?')} bytes)")
        if "message" in r:
            a(f"- Error: {r['message']}")
        a("")

    a("## Deployment Instructions")
    a("")
    a("### C (gcc)")
    a("```bash")
    a("gcc -O3 -mavx2 -lm -o flux_check flux_check.c")
    a("./flux_check")
    a("```")
    a("")
    a("### WebAssembly")
    a("```bash")
    a("wat2wasm flux_check.wat -o flux_check.wasm")
    a("```")
    a("")
    a("### Verilog (FPGA)")
    a("```bash")
    a("iverilog -o flux_check.vvp flux_check.v")
    a("vvp flux_check.vvp")
    a("```")
    a("")
    a("### ARM Cortex-M4")
    a("```bash")
    a("arm-none-eabi-as -mcpu=cortex-m4 -mthumb -o flux_check.o flux_check.s")
    a("arm-none-eabi-ld -o flux_check.elf flux_check.o")
    a("```")
    a("")
    a("---")
    a("*Generated by flux_deploy.py — FLUX v4 Deployment Pipeline*")

    (output_dir / "README.md").write_text("\n".join(lines), encoding="utf-8")
