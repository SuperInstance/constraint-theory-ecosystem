def compile_to_wasm(constraints: Constraints, output_path: Union[str, Path]) -> Path:
    """
    Generate a WASM module (WAT format):
    - Export check(f64) -> i32: check single value, return error_mask
    - Export check_batch(ptr, len) -> void: batch check into memory
    - Zero imports — pure computation
    - Uses wat2wasm if available, otherwise outputs WAT
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    n = len(constraints)
    lo_vals = [float(c["lo"]) for c in constraints]
    hi_vals = [float(c["hi"]) for c in constraints]

    lines: List[str] = []
    a = lines.append

    a(";; FLUX Exact Constraint Engine — Auto-generated WASM Deployment")
    a(f";; Constraints: {n}")
    a(";; Zero imports. Pure computation. Deterministic.")
    a(";;")
    a(";; Exports:")
    a(";;   check(f64) -> i32       — single value check, returns error_mask")
    a(";;   check_batch(i32, i32)   — batch check (ptr, len), writes masks to memory")
    a(";;   memory                  — 1 page (64KB)")
    a("")
    a("(module")

    # Memory: 1 page for batch results
    a('  (memory (export "memory") 1 1)')
    a("")

    # Constraint bounds as globals
    for i in range(n):
        a(f"  (global $lo_{i} f64 (f64.const {repr(lo_vals[i])}))")
        a(f"  (global $hi_{i} f64 (f64.const {repr(hi_vals[i])}))")
    a("")

    # ── check(f64) -> i32 ───────────────────────────────────
    a('  (func (export "check") (param $val f64) (result i32)')
    a("    (local $mask i32)")
    a("    (local.set $mask (i32.const 0))")
    a("")
    a("    ;; NaN check: val != val")
    a("    (if (f64.ne (local.get $val) (local.get $val))")
    a("      (then (return (i32.const {}))".format((1 << n) - 1))
    a("    )")
    a("")

    # Per-constraint check
    for i in range(n):
        a(f"    ;; Constraint {i}: [{lo_vals[i]}, {hi_vals[i]}]")
        a(f"    (if (i32.or")
        a(f"          (f64.lt (local.get $val) (global.get $lo_{i}))")
        a(f"          (f64.gt (local.get $val) (global.get $hi_{i}))")
        a(f"        )")
        a(f"      (then")
        a(f"        (local.set $mask (i32.or (local.get $mask) (i32.const {1 << i})))")
        a(f"      )")
        a(f"    )")
        a("")

    a("    (local.get $mask)")
    a("  )")
    a("")

    # ── check_batch(ptr, len) ────────────────────────────────
    a('  (func (export "check_batch") (param $ptr i32) (param $len i32)')
    a("    (local $i i32)")
    a("    (local $val f64)")
    a("    (local $mask i32)")
    a("")
    a("    (local.set $i (i32.const 0))")
    a("    (block $done")
    a("      (loop $loop")
    a("        (br_if $done (i32.ge_u (local.get $i) (local.get $len)))")
    a("")
    a("        ;; Load f64 value from input array")
    a("        ;; Input values start at offset 0x1000")
    a("        (local.set $val (f64.load (i32.add (i32.const 0x1000)")
    a("          (i32.mul (local.get $i) (i32.const 8)))))")
    a("")
    a("        ;; NaN check")
    a("        (if (f64.ne (local.get $val) (local.get $val))")
    a("          (then")
    a("            (local.set $mask (i32.const {}))".format((1 << n) - 1))
    a("          )")
    a("          (else")
    a("            (local.set $mask (i32.const 0))")
    for i in range(n):
        a(f"            (if (i32.or")
        a(f"                  (f64.lt (local.get $val) (global.get $lo_{i}))")
        a(f"                  (f64.gt (local.get $val) (global.get $hi_{i}))")
        a(f"                )")
        a(f"              (then")
        a(f"                (local.set $mask (i32.or (local.get $mask) (i32.const {1 << i})))")
        a(f"              )")
        a(f"            )")
    a("          )")
    a("        )")
    a("")
    a("        ;; Store result mask at output offset")
    a("        ;; Output masks start at offset 0x4000")
    a("        (i32.store8 (i32.add (i32.const 0x4000) (local.get $i))")
    a("          (local.get $mask))")
    a("")
    a("        (local.set $i (i32.add (local.get $i) (i32.const 1)))")
    a("        (br $loop)")
    a("      )")
    a("    )")
    a("  )")
    a("")
    a("  ;; End of module")
    a(")")

    wat_path = output_path if output_path.suffix == ".wat" else output_path.with_suffix(".wat")
    wat_path.write_text("\n".join(lines), encoding="utf-8")

    # Try to compile with wat2wasm
    wasm_path = wat_path.with_suffix(".wasm")
    try:
        result = subprocess.run(
            ["wat2wasm", str(wat_path), "-o", str(wasm_path)],
            capture_output=True, text=True, timeout=30,
        )
        if result.returncode == 0:
            return wasm_path
    except FileNotFoundError:
        pass

    # Return WAT if wat2wasm not available
    return wat_path


