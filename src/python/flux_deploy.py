"""
FLUX v4 Deployment Compilation Pipeline.

Compiles GUARD constraint definitions to different deployment targets:
  - C (with AVX2 SIMD, auto-compiles with gcc -O3 -mavx2)
  - WASM (hand-written WAT, zero imports, pure computation)
  - Verilog (synthesizable, single-clock-cycle, pipelined)
  - ARM Cortex-M4 assembly (Thumb-2, hard-float)

Usage:
    from flux_deploy import deploy, compile_to_c, compile_to_wasm, ...
    from flux_constraint_exact import PRESETS

    deploy("c", PRESETS["automotive_can"], "build/automotive_c")
    deploy("all", PRESETS["automotive_can"], "build/automotive_all")
"""

