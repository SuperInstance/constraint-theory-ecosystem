def compile_to_verilog(constraints: Constraints, output_path: Union[str, Path]) -> Path:
    """
    Generate synthesizable Verilog:
    - Each constraint becomes a comparator
    - Output is an 8-bit error_mask
    - Single clock cycle latency
    - Pipelined for batch throughput
    """
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    n = len(constraints)
    names = [c.get("name", f"C{i}") for i, c in enumerate(constraints)]
    lo_vals = [float(c["lo"]) for c in constraints]
    hi_vals = [float(c["hi"]) for c in constraints]

    lines: List[str] = []
    a = lines.append

    a("/// ------------------------------------------------------------------")
    a("/// FLUX Exact Constraint Engine — Auto-generated Verilog")
    a(f"/// Constraints: {n}")
    a("/// Single clock cycle latency, pipelined for batch throughput")
    a("/// ------------------------------------------------------------------")
    a("")
    a("module flux_checker (")
    a("    input  wire        clk,")
    a("    input  wire        rst_n,")
    a("    input  wire        valid_in,")
    a("    input  wire [63:0] value_in,    // IEEE 754 double")
    a("    output reg  [7:0]  error_mask,")
    a("    output reg         valid_out")
    a(");")
    a("")

    # ── Internal signals ────────────────────────────────────
    a("    wire [63:0] val;")
    a("    reg  stage_valid;")
    a("")
    a("    // Pipeline register")
    a("    always @(posedge clk or negedge rst_n) begin")
    a("        if (!rst_n) begin")
    a("            val         <= 64'd0;")
    a("            stage_valid <= 1'b0;")
    a("        end else begin")
    a("            val         <= value_in;")
    a("            stage_valid <= valid_in;")
    a("        end")
    a("    end")
    a("")

    # ── Constraint comparators ──────────────────────────────
    a("    // Constraint comparators (combinational)")
    a("    wire [7:0] violations;")
    for i in range(n):
        ident = _sanitize_identifier(names[i])
        lo_v = _verilog_real(lo_vals[i])
        hi_v = _verilog_real(hi_vals[i])
        a(f"    wire viol_{ident};")
        a(f"    // {names[i]}: [{lo_vals[i]}, {hi_vals[i]}]")
        a(f"    assign viol_{ident} = ($bitstoreal(val) < {lo_v}) || ($bitstoreal(val) > {hi_v});")
    a("")

    # ── NaN detection ───────────────────────────────────────
    a("    // NaN detection: exponent all 1s, mantissa non-zero")
    a("    wire is_nan;")
    a("    assign is_nan = (val[62:52] == 11'b11111111111) && (val[51:0] != 52'd0);")
    a("")

    # ── Assemble error_mask ─────────────────────────────────
    a("    // Assemble error_mask from violations")
    a("    always @(posedge clk or negedge rst_n) begin")
    a("        if (!rst_n) begin")
    a("            error_mask <= 8'd0;")
    a("            valid_out  <= 1'b0;")
    a("        end else if (stage_valid) begin")
    if n > 0:
        idents = [_sanitize_identifier(names[i]) for i in range(n)]
        mask_bits = " }".join(f", viol_{idents[i]}" for i in range(n))
        remaining = ", 1'b0" * (8 - n) if n < 8 else ""
        a(f"            error_mask <= is_nan ? 8'b{_int_to_bin((1 << n) - 1, 8)} : {{ {mask_bits}{remaining} }};")
    else:
        a("            error_mask <= 8'd0;")
    a("            valid_out  <= 1'b1;")
    a("        end else begin")
    a("            valid_out  <= 1'b0;")
    a("        end")
    a("    end")
    a("")
    a("endmodule")
    a("")

    # ── Testbench ───────────────────────────────────────────
    a("/// ------------------------------------------------------------------")
    a("/// Testbench")
    a("/// ------------------------------------------------------------------")
    a("")
    a("module flux_checker_tb;")
    a("    reg         clk;")
    a("    reg         rst_n;")
    a("    reg         valid_in;")
    a("    reg  [63:0] value_in;")
    a("    wire [7:0]  error_mask;")
    a("    wire        valid_out;")
    a("")
    a("    flux_checker uut (")
    a("        .clk(clk),")
    a("        .rst_n(rst_n),")
    a("        .valid_in(valid_in),")
    a("        .value_in(value_in),")
    a("        .error_mask(error_mask),")
    a("        .valid_out(valid_out)")
    a("    );")
    a("")
    a("    always #5 clk = ~clk;")
    a("")
    a("    initial begin")
    a("        $display(\"=== FLUX Verilog Testbench ===\");")
    a("        clk = 0; rst_n = 0; valid_in = 0; value_in = 0;")
    a("        #10 rst_n = 1;")
    a("")
    # Test each constraint boundary
    for i in range(n):
        ident = _sanitize_identifier(names[i])
        a(f"        // Test {names[i]}")
        a(f"        valid_in = 1; value_in = $realtobits({lo_vals[i]}); #10;")
        a(f"        if (valid_out && error_mask[{i}] !== 1'b0) $display(\"FAIL: {names[i]} lo should pass\");")
        a(f"        valid_in = 1; value_in = $realtobits({hi_vals[i]}); #10;")
        a(f"        if (valid_out && error_mask[{i}] !== 1'b0) $display(\"FAIL: {names[i]} hi should pass\");")
        a(f"        valid_in = 1; value_in = $realtobits({lo_vals[i]} - 0.001); #10;")
        a(f"        if (valid_out && error_mask[{i}] !== 1'b1) $display(\"FAIL: {names[i]} below lo should violate\");")
        a(f"        valid_in = 1; value_in = $realtobits({hi_vals[i]} + 0.001); #10;")
        a(f"        if (valid_out && error_mask[{i}] !== 1'b1) $display(\"FAIL: {names[i]} above hi should violate\");")
        a("")
    a("        valid_in = 0;")
    a('        $display("All tests completed.");')
    a("        $finish;")
    a("    end")
    a("endmodule")

    v_path = output_path if output_path.suffix == ".v" else output_path.with_suffix(".v")
    v_path.write_text("\n".join(lines), encoding="utf-8")
    return v_path


def _int_to_bin(val: int, width: int) -> str:
    """Format integer as binary literal with given width."""
    return format(val & ((1 << width) - 1), f'0{width}b')


