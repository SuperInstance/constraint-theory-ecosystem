Constraint = Dict[str, Any]  # {"lo": float, "hi": float, "name": str}
Constraints = Sequence[Constraint]

# Severity table (matches C header / spec)
_SEVERITY_TABLE = [0, 1, 1, 2, 2, 3, 3, 3, 3]  # index = popcount(error_mask)

_SEVERITY_NAMES = ["PASS", "CAUTION", "WARNING", "CRITICAL"]


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _c_float(v: float) -> str:
    """Format a Python float as a C float literal."""
    if math.isinf(v):
        return "INFINITY" if v > 0 else "(-INFINITY)"
    if math.isnan(v):
        return "NAN"
    s = repr(v)
    # Ensure it looks like a float (has a dot or 'e')
    if "." not in s and "e" not in s and "E" not in s:
        s += ".0f"
    elif not s.endswith("f"):
        s += "f"
    return s


def _c_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _sanitize_identifier(s: str) -> str:
    """Make a string safe for use as a C/Verilog identifier."""
    out = []
    for ch in s:
        if ch.isalnum() or ch == "_":
            out.append(ch)
        else:
            out.append("_")
    return "".join(out) if out else "c0"


def _verilog_real(v: float) -> str:
    """Format a Python float for Verilog real literal."""
    if math.isinf(v):
        return "1.0/0.0" if v > 0 else "-1.0/0.0"
    return repr(v)


