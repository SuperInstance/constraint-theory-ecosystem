@dataclass(frozen=True)
class OpenSet:
    """An open set in a topological space, represented as a frozenset of points."""

    points: frozenset

    def __contains__(self, point: Any) -> bool:
        return point in self.points

    def intersect(self, other: "OpenSet") -> "OpenSet":
        return OpenSet(self.points & other.points)

    def union_with(self, other: "OpenSet") -> "OpenSet":
        return OpenSet(self.points | other.points)

    def is_subset_of(self, other: "OpenSet") -> bool:
        return self.points.issubset(other.points)


@dataclass
class Section:
    """A section of the constraint sheaf over an open set: local constraint result."""

    domain: OpenSet
    data: dict  # point -> constraint result (bool)

    def restrict(self, subdomain: OpenSet) -> "Section":
        """Restrict section to a smaller open set."""
        assert subdomain.is_subset_of(self.domain)
        return Section(
            domain=subdomain,
            data={p: v for p, v in self.data.items() if p in subdomain.points}
        )

    def agrees_with(self, other: "Section", overlap: OpenSet) -> bool:
        """Check if two sections agree on their overlap."""
        for p in overlap.points:
            if p in self.data and p in other.data:
                if self.data[p] != other.data[p]:
                    return False
        return True


class ConstraintSheaf:
    """Sheaf of constraint results on a topological space.

    Assigns to each open set U the set of valid constraint results on U,
    with restriction maps for inclusions V ⊆ U.
    """

    def __init__(self) -> None:
        self._sections: dict[frozenset, Section] = {}

    def assign(self, open_set: OpenSet, section: Section) -> None:
        """Assign a section to an open set."""
        assert section.domain.points == open_set.points
        self._sections[open_set.points] = section

    def restrict(self, domain: OpenSet, subdomain: OpenSet) -> Section | None:
        """Restriction map: res_{V,U}: F(U) → F(V)."""
        if domain.points in self._sections:
            return self._sections[domain.points].restrict(subdomain)
        return None

    def glue(self, sections: list[Section], cover: list[OpenSet]) -> Section | None:
        """Try to glue local sections into a global section.

        Returns None if sections don't agree on overlaps (sheaf condition fails).
        """
        if not sections:
            return None

        # Check pairwise agreement on overlaps
        for i in range(len(sections)):
            for j in range(i + 1, len(sections)):
                overlap = cover[i].intersect(cover[j])
                if overlap.points and not sections[i].agrees_with(sections[j], overlap):
                    return None  # Sheaf condition fails

        # Glue: merge data from all sections
        merged_data: dict = {}
        merged_points: set = set()
        for s in sections:
            merged_points.update(s.domain.points)
            for p, v in s.data.items():
                if p in merged_data and merged_data[p] != v:
                    return None  # Conflict
                merged_data[p] = v

        return Section(domain=OpenSet(frozenset(merged_points)), data=merged_data)

    def h1_obstruction(self, cover: list[OpenSet], local_sections: list[Section]) -> dict | None:
        """Compute H^1 obstruction: measure of global constraint conflict.

        Returns the cocycle (disagreements on overlaps) if any, or None if trivial.
        """
        obstructions: dict = {}
        for i in range(len(local_sections)):
            for j in range(i + 1, len(local_sections)):
                overlap = cover[i].intersect(cover[j])
                if overlap.points:
                    for p in overlap.points:
                        if (p in local_sections[i].data and
                                p in local_sections[j].data and
                                local_sections[i].data[p] != local_sections[j].data[p]):
                            key = (i, j, p)
                            obstructions[key] = {
                                "section_i": local_sections[i].data[p],
                                "section_j": local_sections[j].data[p],
                            }
        return obstructions if obstructions else None


# ═══════════════════════════════════════════════════════════
#  Natural Transformations Between Strategies
# ═══════════════════════════════════════════════════════════

class CheckerStrategy(Enum):
    EXACT = "exact"
    PREDICTIVE = "predictive"  # overapproximation
    SAMPLING = "sampling"      # underapproximation


@dataclass
class StrategyFunctor:
    """A constraint-checking strategy as a functor from ConstraintSets to BoolAlg."""

    strategy: CheckerStrategy

    def apply(self, cs: ConstraintSet) -> BooleanAlgebra:
        ba = cs.boolean_algebra()
        if self.strategy == CheckerStrategy.EXACT:
            return ba
        elif self.strategy == CheckerStrategy.PREDICTIVE:
            # Overapproximation: add the full carrier as a definable set
            # and close (for demo, return the full powerset)
            return self._powerset(ba.carrier)
        else:  # SAMPLING
            # Underapproximation: return only {empty, carrier}
            return BooleanAlgebra(
                ba.carrier,
                frozenset({frozenset(), ba.carrier})
            )

    @staticmethod
    def _powerset(carrier: frozenset) -> BooleanAlgebra:
        """Full powerset Boolean algebra."""
        from itertools import chain, combinations
        ps = frozenset(
            frozenset(combo)
            for r in range(len(carrier) + 1)
            for combo in combinations(carrier, r)
        )
        return BooleanAlgebra(carrier, ps)


@dataclass
class NaturalTransformation:
    """A natural transformation between two checker strategies."""

    source_strategy: CheckerStrategy
    target_strategy: CheckerStrategy

    def component(self, cs: ConstraintSet) -> Callable[[frozenset], frozenset]:
        """η_C: F(C) → G(C) for a given constraint set C.

        Returns a function mapping definable subsets in the source to the target.
        """
        source_ba = StrategyFunctor(self.source_strategy).apply(cs)
        target_ba = StrategyFunctor(self.target_strategy).apply(cs)

        if self.source_strategy == CheckerStrategy.SAMPLING and \
                self.target_strategy == CheckerStrategy.EXACT:
            # Inclusion: sampling ⊆ exact
            def eta(s: frozenset) -> frozenset:
                assert s in source_ba.elements
                assert s in target_ba.elements
                return s
            return eta

        elif self.source_strategy == CheckerStrategy.EXACT and \
                self.target_strategy == CheckerStrategy.PREDICTIVE:
            # Inclusion: exact ⊆ predictive
            def eta(s: frozenset) -> frozenset:
                assert s in source_ba.elements
                assert s in target_ba.elements
                return s
            return eta

        else:
            # Generic: identity on common elements
            def eta(s: frozenset) -> frozenset:
                return s
            return eta

    def is_sound(self, cs: ConstraintSet) -> bool:
        """Soundness: η_C(S) ⊆ S for all S — no false positives."""
        source_ba = StrategyFunctor(self.source_strategy).apply(cs)
        eta = self.component(cs)
        for s in source_ba.elements:
            result = eta(s)
            if not result.issubset(s):
                return False
        return True

    def is_complete(self, cs: ConstraintSet) -> bool:
        """Completeness: S ⊆ η_C(S) for all S — no false negatives."""
        source_ba = StrategyFunctor(self.source_strategy).apply(cs)
        eta = self.component(cs)
        for s in source_ba.elements:
            result = eta(s)
            if not s.issubset(result):
                return False
        return True
