"""
flux_category.py — Category-theoretic foundations for constraint systems.

Implements:
- ConstraintFunctor: functor from constraint sets to Boolean algebras
- ConstraintMonad: the Checked monad (and comonad) for constraint checking
- ConstraintSheaf: sheaf of constraint results with gluing and cohomology
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import (
    Any,
    Callable,
    Generic,
    TypeVar,
    Hashable,
)

T = TypeVar("T")
U = TypeVar("U")


# ═══════════════════════════════════════════════════════════
#  Boolean Algebra of Definable Subsets
# ═══════════════════════════════════════════════════════════

class BooleanAlgebra:
    """Finite Boolean algebra represented as a collection of subsets of a carrier set."""

    def __init__(self, carrier: frozenset, definable: frozenset[frozenset]):
        """
        Args:
            carrier: the underlying set (as frozenset)
            definable: collection of definable subsets (each a frozenset)
        """
        self.carrier = carrier
        self._definable = definable
        # Verify closure under Boolean operations
        self._verify_axioms()

    def _verify_axioms(self) -> None:
        # Must contain bottom and top
        assert frozenset() in self._definable, "Must contain empty set"
        assert self.carrier in self._definable, "Must contain carrier"
        # Closed under complement
        for s in self._definable:
            comp = self.carrier - s
            assert comp in self._definable, f"Not closed under complement: {comp}"
        # Closed under pairwise union and intersection
        elements = list(self._definable)
        for i, a in enumerate(elements):
            for b in elements[i + 1:]:
                assert (a | b) in self._definable, f"Not closed under union: {a | b}"
                assert (a & b) in self._definable, f"Not closed under intersection: {a & b}"

    @property
    def elements(self) -> frozenset[frozenset]:
        return self._definable

    def complement(self, s: frozenset) -> frozenset:
        assert s in self._definable
        return self.carrier - s

    def union(self, a: frozenset, b: frozenset) -> frozenset:
        assert a in self._definable and b in self._definable
        return a | b

    def intersection(self, a: frozenset, b: frozenset) -> frozenset:
        assert a in self._definable and b in self._definable
        return a & b

    def top(self) -> frozenset:
        return self.carrier

    def bottom(self) -> frozenset:
        return frozenset()

    def __eq__(self, other: object) -> bool:
        if not isinstance(other, BooleanAlgebra):
            return NotImplemented
        return self.carrier == other.carrier and self._definable == other._definable

    def __hash__(self) -> int:
        return hash((self.carrier, self._definable))

    def __repr__(self) -> str:
        return f"BA(carrier={set(self.carrier)}, |{len(self._definable)} elements)"


# ═══════════════════════════════════════════════════════════
#  Constraint Set and the Definable-Subset Functor
# ═══════════════════════════════════════════════════════════

@dataclass(frozen=True)
class ConstraintSet:
    """A constraint set: a carrier set plus a collection of constraint predicates."""

    carrier: frozenset
    # Each constraint is a frozenset (the satisfying subset)
    constraints: frozenset[frozenset] = field(default_factory=frozenset)

    def is_separated(self) -> bool:
        """Check if definable subsets separate all points."""
        ba = self.boolean_algebra()
        for x in self.carrier:
            for y in self.carrier:
                if x != y:
                    # Find a definable set containing x but not y
                    found = False
                    for s in ba.elements:
                        if x in s and y not in s:
                            found = True
                            break
                    if not found:
                        return False
        return True

    def boolean_algebra(self) -> BooleanAlgebra:
        """Compute the Boolean algebra of definable subsets.

        Generated by closing the constraint subsets under complement,
        union, and intersection.
        """
        if not self.carrier:
            return BooleanAlgebra(
                frozenset(),
                frozenset({frozenset()})
            )

        # Start with given constraints + empty + carrier
        current: set[frozenset] = {frozenset(), self.carrier}
        current.update(self.constraints)

        # Close under Boolean operations (iterate to fixed point)
        changed = True
        while changed:
            changed = False
            to_add: set[frozenset] = set()
            elements = list(current)
            for s in elements:
                comp = self.carrier - s
                if comp not in current:
                    to_add.add(comp)
            for i, a in enumerate(elements):
                for b in elements[i + 1:]:
                    u = a | b
                    inter = a & b
                    if u not in current:
                        to_add.add(u)
                    if inter not in current:
                        to_add.add(inter)
            if to_add:
                current.update(to_add)
                changed = True

        return BooleanAlgebra(self.carrier, frozenset(current))


@dataclass(frozen=True)
class ConstraintMorphism:
    """A constraint-preserving function between constraint sets."""

    source: ConstraintSet
    target: ConstraintSet
    mapping: dict  # element -> element

    def __post_init__(self) -> None:
        # Verify it's a valid function
        for x in self.source.carrier:
            assert x in self.mapping, f"Missing mapping for {x}"
            assert self.mapping[x] in self.target.carrier, f"Maps outside target"

    def apply(self, element: Any) -> Any:
        return self.mapping[element]

    def preimage(self, subset: frozenset) -> frozenset:
        """f^{-1}(S) for S ⊆ target."""
        return frozenset(x for x in self.source.carrier if self.mapping[x] in subset)

    def is_constraint_preserving(self) -> bool:
        """Check if preimage of every definable subset is definable."""
        target_ba = self.target.boolean_algebra()
        source_ba = self.source.boolean_algebra()
        for s in target_ba.elements:
            pre = self.preimage(s)
            if pre not in source_ba.elements:
                return False
        return True

    def functor_image(self) -> "BAHomomorphism":
        """Compute F(f): the Boolean algebra homomorphism induced by this morphism.

        F is contravariant: F(f): F(target) → F(source) via preimage.
        """
        assert self.is_constraint_preserving(), "Not constraint-preserving"
        target_ba = self.target.boolean_algebra()
        mapping = {}
        for s in target_ba.elements:
            mapping[s] = self.preimage(s)
        return BAHomomorphism(
            source=target_ba,
            target=target_ba,  # just for structural typing
            preimage_map=mapping,
        )


@dataclass(frozen=True)
class BAHomomorphism:
    """A Boolean algebra homomorphism (via preimage)."""
    source: BooleanAlgebra
    target: BooleanAlgebra
    preimage_map: dict[frozenset, frozenset]


# ═══════════════════════════════════════════════════════════
#  The Constraint Monad (Checked)
# ═══════════════════════════════════════════════════════════

class CheckStatus(Enum):
    OK = "ok"
    FAILED = "failed"


@dataclass(frozen=True)
class Checked(Generic[T]):
    """The constraint-checking monad: Checked[T] is either Ok(value) or Failed(error)."""

    status: CheckStatus
    value: T | None = None
    error: str | None = None

    @staticmethod
    def ok(value: T) -> "Checked[T]":
        return Checked(status=CheckStatus.OK, value=value)

    @staticmethod
    def failed(error: str) -> "Checked[T]":
        return Checked(status=CheckStatus.FAILED, error=error)

    # ── Monad operations ──

    @staticmethod
    def ret(value: T) -> "Checked[T]":
        """return :: a -> Checked a  (trivial always-true constraint)"""
        return Checked.ok(value)

    def bind(self, f: Callable[[T], "Checked[U]"]) -> "Checked[U]":
        """bind :: Checked a -> (a -> Checked b) -> Checked b"""
        if self.status == CheckStatus.FAILED:
            return Checked.failed(self.error)  # type: ignore
        return f(self.value)  # type: ignore

    def __rshift__(self, f: Callable[[T], "Checked[U]"]) -> "Checked[U]":
        """Operator >>= for convenient chaining."""
        return self.bind(f)

    # ── Comonad operations ──

    def extract(self) -> T:
        """extract :: Checked a -> a (fails on invalid)"""
        if self.status == CheckStatus.FAILED:
            raise ValueError(f"Cannot extract from Failed: {self.error}")
        return self.value  # type: ignore

    def duplicate(self) -> "Checked[Checked[T]]":
        """duplicate :: Checked a -> Checked (Checked a)"""
        if self.status == CheckStatus.FAILED:
            return Checked.failed(self.error)  # type: ignore
        return Checked.ok(Checked.ok(self.value))  # type: ignore

    # ── Functor ──

    def fmap(self, f: Callable[[T], U]) -> "Checked[U]":
        """fmap :: (a -> b) -> Checked a -> Checked b"""
        if self.status == CheckStatus.FAILED:
            return Checked.failed(self.error)  # type: ignore
        return Checked.ok(f(self.value))  # type: ignore

    def __repr__(self) -> str:
        if self.status == CheckStatus.OK:
            return f"Ok({self.value!r})"
        return f"Failed({self.error!r})"


